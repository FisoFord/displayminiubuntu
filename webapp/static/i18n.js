const LANG_NAMES = {
  es: 'Español',
  en: 'English',
  pt: 'Português',
  fr: 'Français',
  it: 'Italiano',
};

const LANG_LOCALES = {
  es: 'es-ES',
  en: 'en-US',
  pt: 'pt-BR',
  fr: 'fr-FR',
  it: 'it-IT',
};

let LANG = (() => {
  const saved = localStorage.getItem('md-lang');
  return (saved && I18N[saved]) ? saved : 'es';
})();

function t(key, vars = {}, fallback = null) {
  const dict = I18N[LANG] || I18N.es;
  let text = dict[key] ?? I18N.es[key];
  if (text == null) return fallback == null ? key : fallback;
  for (const [name, value] of Object.entries(vars)) {
    text = text.split('{' + name + '}').join(String(value));
  }
  return text;
}

function locale() {
  return LANG_LOCALES[LANG] || 'es-ES';
}

function applyStaticTranslations() {
  document.documentElement.lang = LANG;
  document.title = t('doc.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.alt = t(el.dataset.i18nAlt);
  });
}

function setLang(lang) {
  if (!I18N[lang]) return false;
  LANG = lang;
  localStorage.setItem('md-lang', lang);
  applyStaticTranslations();
  return true;
}

function buildLangSelect() {
  const select = document.getElementById('langSelect');
  if (!select) return;
  select.innerHTML = Object.entries(LANG_NAMES)
    .map(([code, name]) => `<option value="${code}">${name}</option>`)
    .join('');
  select.value = LANG;
  select.title = t('lang.title');
}
